export function renderHeroBanner(containerEl: HTMLElement, opts: {
	title: string;
	badge: string;
	desc: string;
	iconSvg: string;
}) {
	const banner = containerEl.createDiv({ cls: 'avm-hero-banner' });
	const logo = banner.createDiv({ cls: 'avm-hero-logo' });
	logo.innerHTML = opts.iconSvg;

	const body = banner.createDiv({ cls: 'avm-hero-body' });
	const titleRow = body.createDiv({ cls: 'avm-hero-title-row' });
	titleRow.createDiv({ text: opts.title, cls: 'avm-hero-title' });
	titleRow.createSpan({ text: opts.badge, cls: 'avm-hero-badge' });

	body.createDiv({ text: opts.desc, cls: 'avm-hero-desc' });
	return banner;
}

export function renderDonateBanner(containerEl: HTMLElement, t: {
	donateTitle: string;
	donateDesc: string;
	donateBtn: string;
}) {
	const banner = containerEl.createDiv({ cls: 'avm-donate-banner' });
	const left = banner.createDiv({ cls: 'avm-donate-banner-left' });

	const logo = left.createDiv({ cls: 'avm-donate-logo' });
	logo.innerHTML = AVM_ICONS.heart;

	const content = left.createDiv({ cls: 'avm-donate-content' });
	content.createDiv({ text: t.donateTitle, cls: 'avm-donate-title' });
	content.createDiv({ text: t.donateDesc, cls: 'avm-donate-desc' });

	const btn = banner.createEl('a', {
		cls: 'avm-btn-donate',
		text: t.donateBtn,
		href: 'https://www.donationalerts.com/r/dackseal'
	});
	btn.setAttribute('target', '_blank');
	btn.setAttribute('rel', 'noopener noreferrer');

	const iconSpan = createSpan();
	iconSpan.innerHTML = AVM_ICONS.externalLink;
	btn.appendChild(iconSpan);

	return banner;
}

export function createSectionHeading(containerEl: HTMLElement, title: string, iconSvg?: string): HTMLElement {
	const heading = containerEl.createEl('div', { cls: 'setting-item setting-item-heading avm-section-heading' });
	const info = heading.createDiv({ cls: 'setting-item-info' });
	const name = info.createDiv({ cls: 'setting-item-name' });
	if (iconSvg) {
		const iconSpan = name.createSpan({ cls: 'avm-heading-icon' });
		iconSpan.innerHTML = iconSvg;
	}
	name.createSpan({ text: title });
	return heading;
}
