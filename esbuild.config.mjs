import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Plugin: obsidian-avm-file-extensions
*/
`;

const prod = process.argv[2] === 'production';
const pluginDir = path.resolve('.obsidian/plugins/obsidian-avm-file-extensions');

function syncAssets() {
	if (!fs.existsSync(pluginDir)) {
		fs.mkdirSync(pluginDir, { recursive: true });
	}
	if (fs.existsSync('manifest.json')) {
		fs.copyFileSync('manifest.json', path.join(pluginDir, 'manifest.json'));
	}
	if (fs.existsSync('styles.css')) {
		fs.copyFileSync('styles.css', path.join(pluginDir, 'styles.css'));
	}
}

syncAssets();

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: path.join(pluginDir, 'main.js'),
	minify: prod,
	plugins: [
		{
			name: 'copy-to-root-on-build',
			setup(build) {
				build.onEnd(() => {
					syncAssets();
					const srcMain = path.join(pluginDir, 'main.js');
					if (fs.existsSync(srcMain)) {
						fs.copyFileSync(srcMain, 'main.js');
					}
				});
			},
		},
	],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
